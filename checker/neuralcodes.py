"""
neuralcodes.py - small, exact helpers for combinatorial neural codes.

A code is a set of codewords; each codeword is a frozenset of neuron labels.
Everything here is pure combinatorics (no floating point anywhere).
"""
from itertools import combinations, permutations


# ---------- basic objects ----------

def make_code(codewords):
    """Turn lists like [[1,2],[3],[]] into a set of frozensets (always adds the empty codeword)."""
    code = {frozenset(c) for c in codewords}
    code.add(frozenset())
    return code


def facets(code):
    """Maximal codewords: not strictly contained in any other codeword."""
    return {c for c in code if c and not any(c < d for d in code)}


def in_complex(sigma, facet_set):
    """sigma is a face of Delta(C) iff it sits inside some maximal codeword."""
    return any(sigma <= F for F in facet_set)


def facet_intersections(facet_set):
    """All nonempty intersections of 2 or more facets (the 'max-intersection faces')."""
    out = set()
    fl = list(facet_set)
    for k in range(2, len(fl) + 1):
        for group in combinations(fl, k):
            inter = frozenset.intersection(*group)
            if inter:
                out.add(inter)
    return out


# ---------- topology of links ----------

def link_facets(sigma, facet_set):
    """Facets of Lk(sigma) = {F minus sigma : F a facet containing sigma}, keeping only maximal ones."""
    raw = {F - sigma for F in facet_set if sigma <= F}
    return {L for L in raw if not any(L < M for M in raw)}


def all_faces(facet_list):
    """Every nonempty face of the complex generated by these facets."""
    faces = set()
    for F in facet_list:
        items = sorted(F)
        for k in range(1, len(items) + 1):
            for sub in combinations(items, k):
                faces.add(frozenset(sub))
    return faces


def is_collapsible(facet_list):
    """
    True if the complex collapses to a single vertex.
    Tries EVERY order of elementary collapses (memoized), so it never gets
    stuck the way a greedy collapse can. Fine here: links have <= 5 vertices.
    """
    start = frozenset(all_faces(facet_list))
    seen = {}

    def maximal(faces):
        return [f for f in faces if not any(f < g for g in faces)]

    def search(faces):
        if faces in seen:
            return seen[faces]
        if len(faces) == 1:          # a single vertex left
            seen[faces] = True
            return True
        if not faces:                # empty complex is not a point
            seen[faces] = False
            return False
        tops = maximal(faces)
        result = False
        for tau in faces:
            containing = [M for M in tops if tau <= M]
            if len(containing) == 1 and tau != containing[0]:
                # tau is a free face of M: remove every face between tau and M
                M = containing[0]
                new = frozenset(f for f in faces if not (tau <= f <= M))
                if search(new):
                    result = True
                    break
        seen[faces] = result
        return result

    return search(start)


def _rank_gf2(rows):
    """Rank of a 0/1 matrix over GF(2); rows are Python ints used as bit vectors."""
    rank, rows = 0, [r for r in rows if r]
    while rows:
        pivot = rows.pop()
        low = pivot & -pivot
        rows = [r ^ pivot if r & low else r for r in rows]
        rows = [r for r in rows if r]
        rank += 1
    return rank


def reduced_betti_gf2(facet_list):
    """Reduced Betti numbers over GF(2). All zero means 'acyclic'."""
    faces = all_faces(facet_list)
    if not faces:
        return [1]  # empty complex: reduced H_{-1} is nonzero
    by_dim = {}
    for f in faces:
        by_dim.setdefault(len(f) - 1, []).append(f)
    by_dim[-1] = [frozenset()]          # reduced complex includes the empty face
    top = max(by_dim)
    index = {d: {f: i for i, f in enumerate(by_dim[d])} for d in by_dim}
    ranks = {}
    for d in range(0, top + 1):          # boundary map C_d -> C_{d-1}
        rows = []
        for f in by_dim[d]:
            v = 0
            for x in f:
                v |= 1 << index[d - 1][f - {x}]
            rows.append(v)
        ranks[d] = _rank_gf2(rows)
    betti = []
    for d in range(-1, top + 1):
        n = len(by_dim[d])
        betti.append(n - ranks.get(d, 0) - ranks.get(d + 1, 0))
    return betti


def link_is_contractible(sigma, facet_set):
    """
    Returns (True/False, method). Exact on links with <= 5 vertices:
    collapsible => contractible; nonzero homology => not contractible.
    Raises if the two tests ever disagree in an undecidable way.
    """
    L = link_facets(sigma, facet_set)
    if L == {frozenset()}:                 # sigma is a facet: link is {empty}, not contractible
        return False, "facet"
    collapsible = is_collapsible(L)
    acyclic = all(b == 0 for b in reduced_betti_gf2(L))
    if collapsible:
        assert acyclic, "collapsible but not acyclic - impossible, bug"
        return True, "collapse"
    if not acyclic:
        return False, "homology"
    raise RuntimeError(f"UNDECIDED link for {sorted(sigma)}: acyclic but not collapsible")


def mandatory_faces(facet_set):
    """
    Nonempty faces whose link is not contractible.
    Only intersections of facets can be mandatory (any other face has a cone link),
    so I test just those (plus facets, which are always mandatory).
    """
    mand = set(facet_set)
    for sigma in facet_intersections(facet_set):
        if sigma in facet_set:
            continue
        contractible, _ = link_is_contractible(sigma, facet_set)
        if not contractible:
            mand.add(sigma)
    return mand


def minimal_code(facet_set):
    """C_min(Delta) = facets + mandatory faces + empty codeword."""
    return mandatory_faces(facet_set) | {frozenset()}


def has_local_obstruction(code):
    return not mandatory_faces(facets(code)) <= code


def is_max_intersection_complete(code):
    return facet_intersections(facets(code)) <= code


def is_connected(facet_set):
    fl = list(facet_set)
    seen, stack = {0}, [0]
    while stack:
        i = stack.pop()
        for j in range(len(fl)):
            if j not in seen and fl[i] & fl[j]:
                seen.add(j)
                stack.append(j)
    return len(seen) == len(fl)


# ---------- relabeling ----------

def canonical(code, n=6):
    """Smallest relabeled version over all n! permutations - equal iff codes match up to relabeling."""
    best = None
    for p in permutations(range(1, n + 1)):
        relabel = dict(zip(range(1, n + 1), p))
        version = tuple(sorted(tuple(sorted(relabel[i] for i in c)) for c in code))
        if best is None or version < best:
            best = version
    return best


def parse_short(words):
    """'123' -> {1,2,3}; '' -> empty set. Matches the papers' notation."""
    return make_code([[int(ch) for ch in w] for w in words])
